#!/usr/bin/env python3
"""Task 3: generate production .env on the server (root + infra).

No credential is stored in this file. All secrets are read from environment
variables so the script stays safe to publish. Export these before running:

    export ECS_HOST=<server-ip>
    export SOURCE_RPC_URL=<source-chain-rpc-url>
    export DESTINATION_RPC_URL=<destination-chain-rpc-url>
    export RELAYER_PRIVATE_KEY=<hex-private-key>
    export RELAYER_ADDRESS=<relayer-public-address>
    export POSTGRES_PASSWORD=<postgres-password>
"""
from sshlib import run
import os
import secrets
import string


def _require(name: str) -> str:
    """Return a required secret from the environment, or exit with guidance."""
    value = os.environ.get(name)
    if not value:
        raise SystemExit(
            f"ERROR: {name} is not set. Export it from your secrets manager "
            "before running this script. Hardcoded credentials were removed "
            "so this repository can be open-sourced safely."
        )
    return value


# --- Secrets: supplied at runtime, never committed ---
RELAYER_KEY = _require("RELAYER_PRIVATE_KEY")
RELAYER_ADDR = _require("RELAYER_ADDRESS")
SRC_RPC = _require("SOURCE_RPC_URL")
DST_RPC = _require("DESTINATION_RPC_URL")
POSTGRES_PASSWORD = _require("POSTGRES_PASSWORD")

# --- Deployment target (public address is not a secret, but keep it portable) ---
SERVER_HOST = os.environ.get("ECS_HOST", "<YOUR_SERVER_IP>")

# public CCIP constants (official Chainlink CCIP directory)
SRC_SELECTOR = "16015286601757825753"   # Sepolia
DST_SELECTOR = "3478487238524512106"    # Arbitrum Sepolia
SRC_ROUTER = "0x0BF3dE8c5D3e8A2B34D2BEeB17ABfCeBaf363A59"   # Sepolia CCIP router
DST_ROUTER = "0x2a9C5afB0d0e4BAb2BCdaE109EC4b0c4Be15a165"   # Arbitrum Sepolia CCIP router
SRC_USDC = "0x1c7D4B196Cb0C7B01d743Fbc6116a902379C7238"     # Sepolia USDC
DST_USDC = "0x75faf114eafb1BDbe2F0316DF893fd58CE46AA4d"     # Arbitrum Sepolia USDC

# generate a strong APP_SECRET on the server side
gen_secret = ''.join(secrets.choice(string.ascii_letters + string.digits) for _ in range(48))

root_env = f"""# ===== Cross-chain platform production env (generated by deploy agent) =====
# --- Chain / settlement (REAL mode) ---
SETTLEMENT_MODE=real
SOURCE_CHAIN_ID=11155111
DESTINATION_CHAIN_ID=421614
SOURCE_CHAIN_SELECTOR={SRC_SELECTOR}
DESTINATION_CHAIN_SELECTOR={DST_SELECTOR}
SOURCE_RPC_URL={SRC_RPC}
DESTINATION_RPC_URL={DST_RPC}
SOURCE_CCIP_ROUTER={SRC_ROUTER}
DESTINATION_CCIP_ROUTER={DST_ROUTER}
SOURCE_SETTLEMENT_TOKEN={SRC_USDC}
DESTINATION_SETTLEMENT_TOKEN={DST_USDC}
SOURCE_CHAIN_NAME=ethereum-sepolia
DESTINATION_CHAIN_NAME=arbitrum-sepolia

# --- Keys (RELAYER key doubles as deployer) ---
DEPLOYER_PRIVATE_KEY={RELAYER_KEY}
RELAYER_PRIVATE_KEY={RELAYER_KEY}
RELAYER_SIGNER_MODE=env
CHAIN_WORKER_HMAC_SECRET={gen_secret[:32]}
LISTENER_HMAC_KEYS=worker1:{gen_secret[:24]}

# --- Platform / contract placeholders (filled after deploy) ---
REAL_PLATFORM_SIGNER={RELAYER_ADDR}
MOCK_CCIP_SENDER_FOR_ESCROW={RELAYER_ADDR}
REAL_MARKETPLACE_ESCROW_ADDRESS=
REAL_CCIP_RECEIVER_ADDRESS=
REAL_CCIP_SENDER_ADDRESS=
AUTHORIZED_ESCROW=

# --- API / web ---
APP_ENV=production
APP_SECRET={gen_secret}
CORS_ORIGINS=http://{SERVER_HOST}:3000,http://localhost:3000
DATABASE_URL=postgresql+psycopg://agent_market:{POSTGRES_PASSWORD}@postgres:5432/agent_market
NEXT_PUBLIC_API_URL=http://{SERVER_HOST}:8000
NEXT_PUBLIC_ENABLE_MOCK_FALLBACK=false
ZERO_EX_API_URL=https://api.0x.org
ZERO_EX_API_KEY=
CCIP_GAS_LIMIT=300000
RELAYER_LEASE_SECONDS=300
"""

# infra/.env mirrors root for docker-compose (compose reads from infra/)
infra_env = root_env

remote_root = "/opt/agent-crosschain/.env"
remote_infra = "/opt/agent-crosschain/infra/.env"

# write via heredoc to avoid local temp file
write_cmd = f"""
cat > {remote_root} <<'EOF'
{root_env}
EOF
cp {remote_root} {remote_infra}
echo 'wrote root .env and infra/.env'
echo '--- verify (mask secret) ---'
grep -E 'SETTLEMENT_MODE|SOURCE_CHAIN_ID|RELAYER_PRIVATE_KEY|APP_SECRET' {remote_root} | sed -E 's/(=).*/\\1***masked***/'
wc -l {remote_root} {remote_infra}
"""
out, err = run(write_cmd)
print(out)
if err.strip():
    print("ERR:\n", err)
